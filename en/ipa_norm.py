#!/usr/bin/env python3
"""en 音标归一化 —— **本词典英语音标约定的唯一实现**。2026-08-01。

en 专用，不 import 其他语种（见 multilang-decoupling-essence 铁律）。

═══ 只归一「记法噪声」，不碰「真信息」═══
判据（2026-08-01 定，见 docs/FRAMEWORK.md §五之二）：
    **归一之后，源头原本的陈述还能不能从新值复原？**
    能 → 记法噪声，入库归一；不能 → 真信息，一个字节都不动，呈现方式交展示层。

按这条判据分类：

  ✅ 归一（可复原，无损）
     · `.` 音节点        音节切分可由音标推出，且各源切法不一
     · `͡` 连结弧        `d͡ʒ` 与 `dʒ` 是同一个音，纯排版
     · `̯` 非成音节符    `eɪ̯` 就是 `eɪ`，冗余标注
     · `ʰ` 送气          英语清塞音词首必送气，同位异音
     · `‿` 连接符        跨词连读标记，单词条目里无意义
     · `ɫ` → `l`         暗 l 只出现在 coda，位置完全可推
     · ASCII `g` → `ɡ`   U+0067 → U+0261，同形异码
     · **`ɹ` → `r`**     英语 /r/ 只有一个音位，两种写法纯属**内部不一致**
                          （实测 uk 27,007 行用 ɹ vs 11,433 行用 r）。
                          🔴 **方向定为 ɹ→r**，2026-08-01 定，理由按重要性排：
                          ① `ɹ` 是**严式**记音符号、`r` 是**音位**写法，而本词典在 es 上的每一个
                             决定（擦音归塞音、coda 写清音、删严式段）都是**选音位式、弃严式** ——
                             选 ɹ 与自己的约定自相矛盾；
                          ② 剑桥/牛津/朗文**学习词典**的英语 /r/ 全部写 `r`，中国教材同样，
                             而我们的用户就是中国的英语学习者；
                          ③ 英语无 /r/–/ɹ/ 音位对立，改动零信息损失。
                          ⚠️ 我最初定的是反方向（r→ɹ），理由是"ɹ 是现代标准" —— 那优化的是
                             **语音学精确性**，不是划词弹窗的目标，属于优化错对象。
                          ⚠️ r 色化元音 `ɚ`(butter) / `ɝ`(bird) 是**另一回事，不动** ——
                             它们是元音不是辅音，学习词典（含剑桥美音）照样使用。

  🔴 **不动**（真信息，压平即替源头做断言）
     · `(…)` 可选音段    源头说的是"可选"：`əˈbæn.d(ə)n.m(ə)nt`、`ˈfɑː.ðə(ɹ)`。
                          改成有或没有，都是我们替它下的结论。而且正确呈现方式**取决于
                          在看哪一列**（英式非儿化 vs 美式儿化）—— 那是展示逻辑，不是数据事实。
     · `̩` 成音节辅音    `əˈbleɪ.ʃn̩` 直接删会得到没有元音的音节；展开成 `ʃən` 是**另一种
                          音节分析**，不是同一个陈述。
     · `ɾ` 闪音          `ˈbʌɾɚ`(butter) 与 `ˈlæɾɚ`(ladder) 的 ɾ 分别来自 t 和 d，
                          **闪音把两者中和了**，从音标本身无法还原是哪一个 —— 转写就是猜。
                          （理论上可由拼写还原，但只有 176 行，不值得为它建一套对齐。）
     · `ʔ` 喉塞          同上，`ʔ` 代替的是 t 还是别的，音标里看不出来。

═══ 三列 ═══
    phonetic_uk / phonetic_us            本词典约定值
    phonetic_uk_raw / phonetic_us_raw    源值，忠实照搬（可审计、可回滚）
    phonetic_uk_src / phonetic_us_src    来源

⚠️ 另有 `phonetic` 列（ECDICT 遗留，370,203 行）：90 年代教材式记法，
   9.1 万行用**西里尔字母 `ә` (U+04D9)** 冒充 schwa、24.4 万行用 ASCII `'` 代替 `ˈ`。
   用户 2026-08-01 定：**已无参考价值，象征性保留，不作为源、不归一。**

用法：
    import ipa_norm
    ipa_norm.normalize("ˈneɪ̯.tʃə")     # → 'ˈneɪtʃə'
    ipa_norm.non_english("əɖvɵˈkeʈ")    # → {'ɖ','ɵ','ʈ'}  非英语音位字符
    cd en && python3 -m unittest tests.test_ipa_norm
"""
import re

# ── 记法噪声：直接删 ────────────────────────────────────────────────────
DROP = "͡.ʰ‿" + "̯"          # 连结弧 / 音节点 / 送气 / 连接符 / 非成音节符 ̯
_DROP_RX = re.compile("[" + re.escape(DROP) + "]")

# ── 同形异码 / 内部不一致：换 ──────────────────────────────────────────
# 🔴 顺序无关（三条互不影响），但**别加 ɾ→t、ʔ→t**：见文件头，那是猜不是归一。
REPLACE = (("g", "ɡ"),      # ASCII g → IPA ɡ (U+0261)
           ("ɫ", "l"),      # 暗 l 只出现在 coda，位置可推
           ("ɹ", "r"))      # 见下：统一到**音位写法** r，不是严式的 ɹ

# ── 真信息：保留，不出现在上面两张表里 ─────────────────────────────────
KEEP = "()̩ɾʔ"

# ── 英语音位清单（RP + GA + 保守方言）──────────────────────────────────
# ⚠️ 2026-08-01 第一版把 `ɚ`(r 色化 schwa, butter)、`ɝ`(bird)、`x`(loch)、`ʍ`(which)、
#    `-`(词缀条目) 漏在外面，于是把 1,433 + 7,773 行误判成"非英语音位" ——
#    量的是我的清单不全，不是数据脏。补齐后真正越界的只有 318 + 353 行（0.3%）。
CONSONANTS = set("pbtdkɡfvθðszʃʒhmnŋlɹrjwxʍʔɫɾ")
VOWELS = set("iɪeɛæaɑɒɔʊuʌɜəoɐɚɝᵻ")
MARKS = set("ˈˌː.()-͡‿ʰʲ ") | {"̩", "̯", "̃", "̆", "̈"}
INVENTORY = CONSONANTS | VOWELS | MARKS


def normalize(s):
    """记法归一。真信息原样保留。"""
    if not s:
        return s
    s = _DROP_RX.sub("", s)
    for a, b in REPLACE:
        s = s.replace(a, b)
    return s.strip()


def non_english(s):
    """→ 该串里不属于英语音位清单的字符集合（空集＝干净）。

    实测越界的多是**印度英语转写混入英式列**：
    `advocate` → `əɖvɵˈkeʈ`、`alphabet` → `ˈalfɑ.bɛʈ`、`allopathic` → `əˈlo.pə.t̪ʰɪk`
    （卷舌 ʈ ɖ、齿龈化 t̪ʰ、小舌 χ）。
    ⚠️ **只标记，不猜着改** —— 见"错比缺更伤权威"。
    """
    if not s:
        return set()
    return {ch for ch in s if ch not in INVENTORY}


if __name__ == "__main__":
    for v in ("æbˈd͡ʒɛk.ʃn̩", "ˈɛə̯.ɹə.pleɪ̯n", "ˈkʰæt(ə)ɫ", "əˈbæn.d(ə)n.m(ə)nt",
              "ˈbreɪkˌfɑːst", "ˈbʌɾɚ", "d͡ʒʌd͡ʒ", "əɖvɵˈkeʈ"):
        bad = non_english(v)
        print(f"  {v:28} → {normalize(v):24}" + (f"  ⚠️ 越界 {''.join(sorted(bad))}" if bad else ""))
