# ⭐ **俄语上这件事比 ko/vi 容易，因为元描述有一个强信号：它带西里尔字母。**
#    元描述必须点名那个俄语词元，所以一定含西里尔：
#        авиа         → `авиапо́чта (aviapóčta)的縮寫`      ← 元描述
#        его          → `он (on) 的賓格：他`                ← 元描述**夹着真释义**
#        оно          → `о́ный (ónyj) 的短中性單數`          ← 纯元描述
