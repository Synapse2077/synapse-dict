#   · 本判据只看文本形式，不回源 —— ko 的 K24 真正的判法是**拿另一版的汉字表记去对**；
#     俄语没有汉字表记这一说，所以这条路不存在，只能靠形式 ＋ 抽样人读。
#   · 「纯中文但其实是元描述」的情形（如 `的短中性單數` 前面的词被省略了）本判据看不见。
